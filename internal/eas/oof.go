// mimeSubject encodes a subject line so non-ASCII titles survive the wire.
func mimeSubject(s string) string { return mime.QEncoding.Encode("utf-8", s) }

// oofSettings is what the Settings command stores for one account.
type oofSettings struct {
	State   int    `json:"state"` // 0 off, 1 on, 2 scheduled
	Start   int64  `json:"start"`
	End     int64  `json:"end"`
	Message string `json:"message"`
}

func oofSettingKey(userID string) string { return "oof." + userID }

// active reports whether a notice should go out at this moment. State 2 means
// "scheduled": the client sends a window and expects the server to honour it.
func (o oofSettings) active(now time.Time) bool {
	switch o.State {
	case 1:
		return true
	case 2:
		ts := now.Unix()
		if o.Start > 0 && ts < o.Start {
			return false
		}
		if o.End > 0 && ts > o.End {
			return false
		}
		return true
	}
	return false
}

func (s *Server) loadOof(userID string) oofSettings {
	var out oofSettings
	raw, err := s.Store.Setting(oofSettingKey(userID))
	if err != nil || strings.TrimSpace(raw) == "" {
		return out
	}
	if err := json.Unmarshal([]byte(raw), &out); err != nil {
		s.Log.Warn("cannot read oof settings", "err", err)
	}
	return out
}

func (s *Server) saveOof(userID string, v oofSettings) error {
	raw, err := json.Marshal(v)
	if err != nil {
		return err
	}
	return s.Store.SetSetting(oofSettingKey(userID), string(raw))
}

// oofResponse answers a Settings/Oof request, applying a Set first when the
// client sends one and always returning the resulting state.
func (s *Server) oofResponse(user *store.User, node *wbxml.Node) *wbxml.Node {
	current := s.loadOof(user.ID)

	if set := node.Child("Set"); set != nil {
		next := current
		if v := set.ChildText("OofState"); v != "" {
			next.State = atoiDefault(v, 0)
		}
		if v := set.ChildText("StartTime"); v != "" {
			if t := parseEasTime(v); !t.IsZero() {
				next.Start = t.Unix()
			}
		}
		if v := set.ChildText("EndTime"); v != "" {
			if t := parseEasTime(v); !t.IsZero() {
				next.End = t.Unix()
			}
		}
		// The reply text lives in the internal-audience message; the external
		// variants are accepted by clients but we keep a single text.
		for _, msg := range set.ChildrenNamed("OofMessage") {
			if msg.Child("AppliesToInternal") == nil {
				continue
			}
			if text := msg.ChildText("ReplyMessage"); text != "" {
				next.Message = text
			}
			break
		}
		if err := s.saveOof(user.ID, next); err != nil {
			s.Log.Warn("cannot store oof settings", "err", err, "user", user.Name)
		} else {
			current = next
		}
	}

	out := wbxml.N(pageSettings, "Oof", wbxml.T(pageSettings, "Status", "1"))
	get := wbxml.N(pageSettings, "Get", wbxml.T(pageSettings, "OofState", itoa(current.State)))
	if current.Start > 0 {
		get.Children = append(get.Children,
			wbxml.T(pageSettings, "StartTime", formatEasCalendarTime(current.Start)))
	}
	if current.End > 0 {
		get.Children = append(get.Children,
			wbxml.T(pageSettings, "EndTime", formatEasCalendarTime(current.End)))
	}
	get.Children = append(get.Children,
		wbxml.N(pageSettings, "OofMessage",
			// AppliesToInternal is a boolean; an empty value leaves the
			// message unusable for clients that need an audience flag.
			wbxml.T(pageSettings, "AppliesToInternal", "1"),
			wbxml.T(pageSettings, "Enabled", "1"),
			wbxml.T(pageSettings, "ReplyMessage", current.Message)),
	)
	out.Children = append(out.Children, get)
	return out
}

// A notice per correspondent per day is enough: without this an autoresponder
// talking to another autoresponder loops forever.
const oofReplyInterval = 24 * time.Hour

var (
	oofMu   sync.Mutex
	oofLast = map[string]time.Time{}
)

func (s *Server) oofRecentlyAnswered(userID, addr string) bool {
	key := userID + "|" + strings.ToLower(addr)
	now := time.Now()
	oofMu.Lock()
	defer oofMu.Unlock()
	if at, ok := oofLast[key]; ok && now.Sub(at) < oofReplyInterval {
		return true
	}
	oofLast[key] = now
	return false
}

// looksAutomated reports whether a message was generated by a machine, in which
// case answering it would start a loop.
func looksAutomated(raw []byte) bool {
	head := raw
	if idx := indexHeaderEnd(raw); idx >= 0 {
		head = raw[:idx]
	}
	lower := strings.ToLower(string(head))
	for _, marker := range []string{
		"auto-submitted:",
		"precedence: bulk",
		"precedence: list",
		"precedence: junk",
		"x-autoreply",
		"list-id:",
	} {
		if strings.Contains(lower, marker) {
			return true
		}
	}
	return false
}

func indexHeaderEnd(raw []byte) int {
	for i := 0; i+3 < len(raw); i++ {
		if raw[i] == '\r' && raw[i+1] == '\n' && raw[i+2] == '\r' && raw[i+3] == '\n' {
			return i
		}
	}
	for i := 0; i+1 < len(raw); i++ {
		if raw[i] == '\n' && raw[i+1] == '\n' {
			return i
		}
	}
	return -1
}

// OofReply answers an inbound message while the account is out of office. It is
// wired into deliver.OnInbound so every entry point behaves the same way.
func (s *Server) OofReply(user *store.User, parsed *mailparse.Message, raw []byte) {
	if user == nil || parsed == nil {
		return
	}
	settings := s.loadOof(user.ID)
	if !settings.active(time.Now()) {
		return
	}
	from := strings.TrimSpace(parsed.FromAddr)
	if from == "" || strings.EqualFold(from, user.Address) {
		return
	}
	if looksAutomated(raw) {
		return
	}
	// Meeting invitations and replies are handled by the calendar logic; an
	// auto-reply there would only confuse the organiser's client.
	if hasCalendarPart(parsed) {
		return
	}
	if s.oofRecentlyAnswered(user.ID, from) {
		return
	}

	text := strings.TrimSpace(settings.Message)
	if text == "" {
		text = "I am currently out of the office and will reply when I am back."
	}
	name := user.DisplayName
	if name == "" {
		name = user.Name
	}
	subject := parsed.Subject
	if subject == "" {
		subject = "(no subject)"
	}

	var b strings.Builder
	b.WriteString("From: " + (&mail.Address{Name: name, Address: user.Address}).String() + "\r\n")
	b.WriteString("To: " + from + "\r\n")
	b.WriteString("Subject: " + mimeSubject("Auto: "+subject) + "\r\n")
	b.WriteString("Date: " + time.Now().UTC().Format(time.RFC1123Z) + "\r\n")
	b.WriteString("MIME-Version: 1.0\r\n")
	b.WriteString("Content-Type: text/plain; charset=utf-8\r\n")
	b.WriteString("Content-Transfer-Encoding: 8bit\r\n")
	b.WriteString("Auto-Submitted: auto-replied\r\n")
	b.WriteString("\r\n")
	b.WriteString(text + "\r\n")

	node := wbxml.N(pageComposeMail, "SendMail",
		wbxml.T(pageComposeMail, "Mime", base64.StdEncoding.EncodeToString([]byte(b.String()))))
	if status := s.sendComposed(user, node, false); status != "1" {
		s.Log.Warn("out-of-office reply not delivered", "status", status,
			"user", user.Name, "to", from)
		return
	}
	s.Log.Info("out-of-office reply sent", "user", user.Name, "to", from)
}
